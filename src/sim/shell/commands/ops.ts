export const crontab: Command = {
  name: "crontab",
  summary: "your scheduled jobs (crontab -l lists, crontab -e edits)",
  run(ctx) {
    const { flags, args } = flagSet(ctx.argv.slice(1));
    const ui = ctx.argv.indexOf("-u");
    const user = ui >= 0 ? (ctx.argv[ui + 1] ?? ctx.user) : ctx.user;
    if (user !== ctx.user && ctx.user !== "root") {
      ctx.err("must be privileged to use -u");
      return 1;
    }
    if (flags.has("l")) {
      const text = userCrontab(ctx.host, user);
      if (text === undefined) {
        ctx.err(`no crontab for ${user}`);
        return 1;
      }
      ctx.out(text.replace(/\n$/, ""));
      return 0;
    }
    if (flags.has("r")) {
      const spool = getDir(ctx.host, "/var/spool/cron/crontabs");
      if (!spool?.children[user]) {
        ctx.err(`no crontab for ${user}`);
        return 1;
      }
      delete spool.children[user];
      return 0;
    }
    if (flags.has("e")) {
      const current = userCrontab(ctx.host, user);
      if (current === undefined && !getFile(ctx.host, `${ctx.home}/.selected_editor`)) {
        ctx.out(
          [
            `no crontab for ${user} - using an empty one`,
            "",
            "Select an editor.  To change later, run 'select-editor'.",
            "  1. /bin/nano        <---- easiest",
            "  2. /usr/bin/vim.basic",
            "  3. /usr/bin/vim.tiny",
            "  4. /bin/ed",
          ].join("\n"),
        );
        ctx.prompt({ prompt: "\nChoose 1-4 [1]: ", secret: false, data: { user } });
        return 0;
      }
      openEditor(ctx, user);
      return 0;
    }
    // crontab FILE, or crontab - (read from stdin)
    const src = args.find((a) => a !== user);
    let text: string | undefined;
    if (!src || src === "-") text = ctx.stdin;
    else text = getFile(ctx.host, ctx.path(src))?.content;
    if (text === undefined) {
      ctx.err(src ? `${src}: No such file or directory` : "usage: crontab [-u user] { -e | -l | -r | file }");
      return 1;
    }
    const errors = installCrontab(ctx.host, user, text);
    if (errors.length) {
      ctx.err(`${errors[0]}\nerrors in crontab file, can't install.`);
      return 1;
    }
    return 0;
  },
  resume(ctx, p, input) {
    const user = String(p.data.user);
    if (input.trim() && input.trim() !== "1") ctx.info("This game only has nano. Using nano.");
    put(ctx.host, `${ctx.home}/.selected_editor`, file(`# Generated by /usr/bin/select-editor\nSELECTED_EDITOR="/bin/nano"\n`, 0o644, ctx.realUser, ctx.realUser));
    openEditor(ctx, user);
    return 0;
  },
};

function openEditor(ctx: Ctx, user: string) {
  // The real crontab edits a temp file and installs it when you save. Here nano edits the
  // spool file directly, as root, which ends up the same.
  const path = `/var/spool/cron/crontabs/${user}`;
  const content = userCrontab(ctx.host, user) ?? CRONTAB_TEMPLATE;
  if (!getFile(ctx.host, path)) installCrontab(ctx.host, user, content);
  ctx.emit.editor = { host: ctx.frame.host, path, content, canWrite: true, asUser: "root", isNew: false };
}

// ---------- rclone ----------

interface Remote {
  name: string;
  type: string;
}

function remotes(host: Host, home: string): Remote[] {
  const conf = getFile(host, `${home}/.config/rclone/rclone.conf`)?.content ?? "";
  const out: Remote[] = [];
  let cur: Remote | null = null;
  for (const line of conf.split("\n")) {
    const sec = /^\[(.+)\]$/.exec(line.trim());
    if (sec) {
      cur = { name: sec[1], type: "" };
      out.push(cur);
    } else if (cur && /^type\s*=/.test(line)) cur.type = line.split("=")[1].trim();
  }
  return out;
}

/** "offsite:crumb-backups/daily" -> { remote, bucket, prefix } */
function splitRemote(spec: string): { remote: string; bucket: string; prefix: string } | null {
  const m = /^([\w-]+):(.*)$/.exec(spec);
  if (!m) return null;
  const [bucket, ...rest] = m[2].split("/").filter(Boolean);
  return { remote: m[1], bucket: bucket ?? "", prefix: rest.join("/") };
}

function bucketOf(w: World, remote: string, bucket: string) {
  w.storage ??= { buckets: {} };
  const key = `${remote}:${bucket}`;
  return (w.storage.buckets[key] ??= {});
}

export const rclone: Command = {
  name: "rclone",
  summary: "copy files to and from cloud storage (rclone copy DIR remote:bucket)",
  run(ctx) {
    const [sub, a, b] = ctx.argv.slice(1).filter((x) => !x.startsWith("-"));
    const conf = remotes(ctx.host, ctx.home);
    const need = (spec: string) => {
      const r = splitRemote(spec);
      if (!r) return null;
      if (!conf.some((c) => c.name === r.remote)) {
        ctx.err(`${lsTime(ctx.w.clock).replace(/^(\w+) (\d+)/, "2026/10/$2")} CRITICAL: Failed to create file system for "${spec}": didn't find section in config file`);
        return undefined;
      }
      return r;
    };
    switch (sub) {
      case "listremotes":
        ctx.out(conf.map((c) => `${c.name}:`).join("\n"));
        return 0;
      case "copy": {
        if (!a || !b) {
          ctx.err('Command copy needs 2 arguments maximum: you provided 0 non flag arguments: []');
          return 1;
        }
        if (/^[\w-]+:/.test(a)) {
          // download: rclone copy remote:bucket/file /local/dir
          const r = need(a);
          if (!r) return 1;
          const store = bucketOf(ctx.w, r.remote, r.bucket);
          const hits = Object.entries(store).filter(([k]) => !r.prefix || k === r.prefix || k.startsWith(r.prefix + "/"));
          for (const [k, v] of hits) {
            const err = writeFile(ctx.host, ctx.user, `${ctx.path(b)}/${basename(k)}`, v.content);
            if (err) {
              ctx.err(`ERROR : ${basename(k)}: Failed to copy: ${err === "EACCES" ? "permission denied" : "directory not found"}`);
              return 1;
            }
          }
          return 0;
        }
        const r = need(b);
        if (!r) return 1;
        const src = ctx.path(a);
        const d = getDir(ctx.host, src);
        const one = getFile(ctx.host, src);
        const files: [string, string, number][] = d
          ? Object.entries(d.children).flatMap(([n, node]) => (node.type === "file" ? [[n, node.content, node.content.length + (node.padBytes ?? 0)] as [string, string, number]] : []))
          : one
            ? [[basename(src), one.content, one.content.length + (one.padBytes ?? 0)]]
            : [];
        if (!d && !one) {
          ctx.err(`ERROR : directory not found: ${a}`);
          return 1;
        }
        const store = bucketOf(ctx.w, r.remote, r.bucket);
        for (const [n, content, size] of files) store[r.prefix ? `${r.prefix}/${n}` : n] = { content, sizeBytes: size, at: ctx.w.clock };
        if (ctx.argv.includes("-P") || ctx.argv.includes("--progress")) {
          const total = files.reduce((s, f) => s + f[2], 0);
          ctx.out(`Transferred:   \t${(total / 1024).toFixed(3)} KiB / ${(total / 1024).toFixed(3)} KiB, 100%, 0 B/s, ETA -\nTransferred:            ${files.length} / ${files.length}, 100%\nElapsed time:         1.2s`);
        }
        return 0;
      }
      case "ls": {
        const r = a && need(a);
        if (!r) return 1;
        const store = bucketOf(ctx.w, r.remote, r.bucket);
        ctx.out(
          Object.entries(store)
            .filter(([k]) => !r.prefix || k.startsWith(r.prefix))
            .map(([k, v]) => `${String(v.sizeBytes).padStart(9)} ${k}`)
            .join("\n"),
        );
        return 0;
      }
      case "lsd": {
        const r = a && need(a);
        if (!r) return 1;
        const names = Object.keys(ctx.w.storage?.buckets ?? {}).filter((k) => k.startsWith(`${r.remote}:`)).map((k) => k.split(":")[1]);
        ctx.out(names.map((n) => `          -1 2026-10-11 09:00:00        -1 ${n}`).join("\n"));
        return 0;
      }
      default:
        ctx.err(`Error: unknown command "${sub ?? ""}" for "rclone"\nRun 'rclone --help' for usage.`);
        return 1;
    }
  },
};

// ---------- reboot ----------

export const reboot: Command = {
  name: "reboot",
  summary: "restart the whole server (sudo reboot)",
  run(ctx) {
    if (ctx.user !== "root") {
      ctx.err("Call to Reboot failed: Interactive authentication required.");
      ctx.info("Rebooting needs root: sudo reboot");
      return 1;
    }
    if (ctx.frame.host !== "vps") {
      ctx.info("Rebooting your own laptop is not in this game.");
      return 0;
    }
    const w = ctx.w;
    const host = ctx.host;
    for (const c of Object.values(host.docker.containers)) if (c.status === "running" || c.status === "restarting") stopContainer(w, host, c, false);
    advance(w, w.clock + 45);
    for (const s of Object.values(host.services)) {
      s.state = s.enabled || s.triggeredBy ? "active" : "inactive";
      s.since = w.clock;
    }
    host.journal.push({ t: w.clock, unit: "systemd", msg: "Startup finished in 2.104s (kernel) + 9.873s (userspace) = 11.977s." });
    // Docker brings back containers by their restart policy.
    if (host.services.docker?.state === "active") {
      for (const c of Object.values(host.docker.containers)) {
        if (c.restart === "always" || (c.restart === "unless-stopped" && !c.manuallyStopped)) startContainer(w, host, c, w.clock);
      }
    }
    // Everyone logged in to web-1 is thrown back to the laptop.
    const lost = ctx.sh.frames.findIndex((f) => f.host === "vps");
    if (lost > 0) ctx.sh.frames.length = lost;
    ctx.err(`Connection to ${host.publicIp} closed by remote host.\nConnection to ${host.publicIp} closed.`);
    return 0;
  },
};

export const OPS_COMMANDS = [crontab, rclone, reboot];
